/**
 * Generates src/preview/registry.tsx and src/preview/names.ts from the demo
 * files in src/preview/demos/. Run with: npm run generate:preview
 *
 * Convention: src/preview/demos/<name>-demo.tsx  →  preview name "<name>"
 * (used as <ComponentPreview sandbox="<name>" /> and /preview/<name>).
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const demosDir = path.join(root, "preview", "demos");
const registryPath = path.join(root, "preview", "registry.tsx");
const namesPath = path.join(root, "preview", "names.ts");

const files = fs
  .readdirSync(demosDir)
  .filter((f) => f.endsWith("-demo.tsx"))
  .sort();

const names = files.map((f) => f.replace(/-demo\.tsx$/, ""));

const header = `// AUTO-GENERATED by src/scripts/generate-preview-registry.ts — do not edit.
// Add demos as src/preview/demos/<name>-demo.tsx and run: npm run generate:preview
`;

const registry = `"use client";

${header}
import { type ComponentType, type LazyExoticComponent } from "react";
import { lazyRetry } from "./lazyRetry";

export const sandboxRegistry: Record<string, LazyExoticComponent<ComponentType<any>>> = {
${names.map((n) => `  "${n}": lazyRetry(() => import("./demos/${n}-demo")),`).join("\n")}
};
`;

const namesFile = `${header}
export const sandboxNames = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export type SandboxName = (typeof sandboxNames)[number];
`;

fs.writeFileSync(registryPath, registry);
fs.writeFileSync(namesPath, namesFile);
console.log(`Preview registry generated: ${names.length} demos`);
