import type { Config } from "../config.js";
import { McpToolError, suggestNames } from "../errors.js";
import {
  RegistryFullItemSchema,
  RegistryIndexSchema,
  type RegistryFullItem,
  type RegistryIndexItem,
} from "./types.js";

/**
 * The only component of this server that talks to the network (mcp-guide.md
 * section 18). Fetches and caches the live ShadCN registry; never invents data.
 *
 * Component names are validated against the cached index before ever being
 * interpolated into a URL, which is also the path-traversal defense required
 * by section 25 — an unknown name never reaches `fetch`.
 */

interface CacheEntry<T> {
  value: T;
  expiresAt: number;
}

/** Matches the kebab-case names generated by generate-registry.ts. */
const VALID_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export class RegistryClient {
  private readonly config: Config;
  private indexCache: CacheEntry<Map<string, RegistryIndexItem>> | null = null;
  private readonly itemCache = new Map<string, CacheEntry<RegistryFullItem>>();
  private readonly fetchImpl: typeof fetch;

  constructor(config: Config, fetchImpl: typeof fetch = fetch) {
    this.config = config;
    this.fetchImpl = fetchImpl;
  }

  private now(): number {
    return Date.now();
  }

  /** Fetches and validates `{base}/registry.json`, cached with a TTL. */
  async getIndex(): Promise<Map<string, RegistryIndexItem>> {
    if (this.indexCache && this.indexCache.expiresAt > this.now()) {
      return this.indexCache.value;
    }

    const url = `${this.config.registryBaseUrl}/registry.json`;
    let response: Response;
    try {
      response = await this.fetchImpl(url);
    } catch (cause) {
      throw new McpToolError(
        "REGISTRY_UNAVAILABLE",
        `Could not reach the Algorize UI registry at ${url}.`,
      );
    }

    if (!response.ok) {
      throw new McpToolError(
        "REGISTRY_UNAVAILABLE",
        `Registry index request failed with HTTP ${response.status} at ${url}.`,
      );
    }

    const json = await response.json();
    const parsed = RegistryIndexSchema.safeParse(json);
    if (!parsed.success) {
      throw new McpToolError(
        "REGISTRY_UNAVAILABLE",
        `Registry index at ${url} did not match the expected shape.`,
      );
    }

    const map = new Map(parsed.data.items.map((item) => [item.name, item]));
    this.indexCache = { value: map, expiresAt: this.now() + this.config.registryCacheTtlMs };
    return map;
  }

  async listIndexItems(): Promise<RegistryIndexItem[]> {
    return [...(await this.getIndex()).values()];
  }

  async getIndexItem(name: string): Promise<RegistryIndexItem> {
    const index = await this.getIndex();
    const item = index.get(name);
    if (!item) {
      throw new McpToolError(
        "COMPONENT_NOT_FOUND",
        `Component '${name}' was not found.`,
        suggestNames(name, [...index.keys()]),
      );
    }
    return item;
  }

  /** Fetches the full item (with file contents) for a name already confirmed to exist. */
  async getFullItem(name: string): Promise<RegistryFullItem> {
    if (!VALID_NAME.test(name)) {
      throw new McpToolError("COMPONENT_NOT_FOUND", `'${name}' is not a valid component name.`);
    }

    // Validate against the known index first — an unrecognized name never
    // reaches a URL or a filesystem path (section 25).
    await this.getIndexItem(name);

    const cached = this.itemCache.get(name);
    if (cached && cached.expiresAt > this.now()) {
      return cached.value;
    }

    const url = `${this.config.registryBaseUrl}/${name}.json`;
    let response: Response;
    try {
      response = await this.fetchImpl(url);
    } catch {
      throw new McpToolError("REGISTRY_UNAVAILABLE", `Could not reach ${url}.`);
    }

    if (!response.ok) {
      throw new McpToolError(
        "SOURCE_NOT_FOUND",
        `Registry item '${name}' returned HTTP ${response.status} at ${url}.`,
      );
    }

    const json = await response.json();
    const parsed = RegistryFullItemSchema.safeParse(json);
    if (!parsed.success) {
      throw new McpToolError("REGISTRY_UNAVAILABLE", `Registry item '${name}' at ${url} did not match the expected shape.`);
    }

    this.itemCache.set(name, { value: parsed.data, expiresAt: this.now() + this.config.registryCacheTtlMs });
    return parsed.data;
  }

  /** The public registry URL for an item, e.g. https://.../r/login-form.json */
  itemUrl(name: string): string {
    return `${this.config.registryBaseUrl}/${name}.json`;
  }

  /**
   * Resolves `registryDependencies` into { internal, external } names.
   * Internal = another Algorize item (full URL pointing at our own base URL).
   * External = a bare shadcn name (e.g. "utils") that resolves upstream, not here.
   */
  splitDependencies(registryDependencies: string[]): { internal: string[]; external: string[] } {
    const internal: string[] = [];
    const external: string[] = [];
    const prefix = `${this.config.registryBaseUrl}/`;
    for (const dep of registryDependencies) {
      if (dep.startsWith(prefix) && dep.endsWith(".json")) {
        internal.push(dep.slice(prefix.length, -".json".length));
      } else if (/^https?:\/\//.test(dep)) {
        // A full URL pointing somewhere other than our own registry.
        external.push(dep);
      } else {
        external.push(dep);
      }
    }
    return { internal, external };
  }

  /** Recursively resolves internal registryDependencies, without cycles. */
  async resolveInternalDependenciesRecursive(
    name: string,
    seen: Set<string> = new Set(),
  ): Promise<string[]> {
    if (seen.has(name)) return [];
    seen.add(name);

    const item = await this.getIndexItem(name).catch(() => null);
    if (!item) return [];

    const { internal } = this.splitDependencies(item.registryDependencies);
    const all = new Set(internal);
    for (const dep of internal) {
      const nested = await this.resolveInternalDependenciesRecursive(dep, seen);
      for (const n of nested) all.add(n);
    }
    return [...all];
  }
}
